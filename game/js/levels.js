  function concat(chunks) {
    const h = Math.max(...chunks.map((c) => c.length));
    const out = new Array(h).fill('');
    for (const ch of chunks) {
      const w = Math.max(...ch.map((r) => r.length));
      for (let j = 0; j < h; j++) out[j] += (ch[j] || '').padEnd(w, '.');
    }
    return out;
  }

